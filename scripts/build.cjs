const { buildSync } = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const result = buildSync({ absWorkingDir: root, entryPoints: ['src/worker.cjs'], bundle: true, minify: true, write: false, platform: 'browser', format: 'iife', target: 'es2022', legalComments: 'inline' });
fs.mkdirSync(path.join(root, 'assets'), { recursive: true });
// A classic script containing the worker source keeps file:// usable offline.
fs.writeFileSync(path.join(root, 'assets/tokenizer.js'), '// Generated by scripts/build.cjs. See THIRD_PARTY_NOTICES.md.\n' + 'globalThis.LatigoWorkerSource=' + JSON.stringify(result.outputFiles[0].text) + ';\n');
console.log('Tokenizador local empaquetado. Sin CDN ni descargas al usar la app.');
